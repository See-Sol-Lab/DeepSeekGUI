/**
 * The Session → Markdown renderer for the desktop's "export as Markdown"
 * feature (DeepSeekGUI B8-P1, 2026-09-28): one pure fold from a Session
 * event log to a human-readable document. No disk, no network, no model,
 * no clock — the caller passes the export time, and the desktop owns the
 * file name and the save dialog.
 *
 * The document quotes the log verbatim: what the person said and what the
 * assistant replied, in `seq` order, without rewriting, merging, or
 * summarizing. Command, system, statistics, and internal-diagnostic events
 * are omitted; a slash command is recorded only as `command/run` /
 * `command/done` log events, so it never appears. Synthetic user-role
 * messages (injected context) are not the person speaking and are omitted
 * the same way `session-title` picks eligible human prompts, by
 * `source.kind === 'user'`. With `includeDetails`, reasoning blocks and
 * tool calls ride along as collapsed `<details>` sections at their
 * positions.
 *
 * @module @deepseek-ai/dsh-workbench-inspector/session-markdown
 */

import type { SessionEvent } from '@deepseek-ai/dsh-session/types'
import type { WorkbenchExportLanguage } from './types.ts'

/** The interface language an export is written in (the Remote boundary type lives in `./types`). */
export type SessionMarkdownLanguage = WorkbenchExportLanguage

/** A single tool argument or result longer than this is truncated, with the true original length reported. */
export const SESSION_EXPORT_DETAIL_LIMIT = 4_000

/** UI wording for one export language. */
interface SessionMarkdownLabels {
  readonly user: string
  readonly assistant: string
  readonly exportedAt: string
  readonly workingDirectory: string
  readonly sessionId: string
  readonly notice: string
  readonly attachment: string
  readonly attachmentNote: string
  readonly reasoning: string
  readonly toolSummary: (name: string) => string
  readonly params: string
  readonly result: string
  readonly truncated: (total: number) => string
  readonly notEnded: (detail: string | undefined) => string
  readonly compaction: string
  readonly nonTextResult: string
  readonly empty: string
  readonly untitled: string
}

